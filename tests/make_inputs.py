def _surface(name, kind, construction, boundary, sun, wind, view, vertices):
    lines = [
        "  BuildingSurface:Detailed,",
        f"    {name + ',':25}!- Name",
        f"    {kind + ',':25}!- Surface Type",
        f"    {construction + ',':25}!- Construction Name",
        "    ZONE ONE,                !- Zone Name",
        "    ,                        !- Space Name",
        f"    {boundary + ',':25}!- Outside Boundary Condition",
        "    ,                        !- Outside Boundary Condition Object",
        f"    {sun + ',':25}!- Sun Exposure",
        f"    {wind + ',':25}!- Wind Exposure",
        f"    {view + ',':25}!- View Factor to Ground",
        "    4,                       !- Number of Vertices",
    ]
    for i, vertex in enumerate(vertices, 1):
        lines.append(f"    {vertex}{';' if i == 4 else ','}  !- X,Y,Z ==> Vertex {i} {{m}}")
    return "\n".join(lines) + "\n"


