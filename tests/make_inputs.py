# ---------------------------------------------------------------------------------------
# Large input that makes every Fortran array grow at least once:
#
#   array               initial size   this input
#   IdfObject           20             26 Parametric objects
#   IdfField            200            276 fields in Parametric objects
#   ObjectLines         500            more than 540 objects
#   FoundExpression     100            522 embedded expressions
#   Symbol              500            507 parameters, then more than 500 constants
#   IntCode             1000           more than 1500 codes
#   StrucStack          50             55 nested IF blocks
#   EvalStack           50             60 values left on the stack by MOD (see PORTING_NOTES.md)
#   ErrMsgs             100            105 warnings
#
# Only the first case is run (Parametric:RunControl) to keep the expected output small.
# ---------------------------------------------------------------------------------------
def large_input_block():
    num_cases, num_parameters, num_objects = 10, 25, 520
    lines = ["  Parametric:RunControl, Runs, Yes" + ", No" * (num_cases - 1) + ";"]
    for p in range(1, num_parameters + 1):
        values = ", ".join(str(p * 10 + c) for c in range(num_cases))
        lines.append(f"  Parametric:SetValueForRun, $p{p}, {values};")
    logic = ["PARAMETER $depth", "PARAMETER $q"]
    logic += [f"PARAMETER $extra{i}" for i in range(480)]
    logic += ["IF 1"] * 55 + ["$depth = 99"] + ["ENDIF"] * 55
    logic += ["$q = MOD(7~3)"] * 60
    logic += [f"NOT A STATEMENT {i}" for i in range(105)]
    lines.append("  Parametric:Logic, Main,\n    " + ",\n    ".join(logic) + ";")
    lines.append("")
    # 520 small detached shading surfaces in a row south of the building
    for i in range(1, num_objects + 1):
        lines.append(f"  Shading:Site, Obj{i}, 0, 90, =$p{(i % num_parameters) + 1} + {i}, -40, 0, 0.5, 1;")
    lines.append("")
    lines.append(sink("=$depth").rstrip("\n"))
    lines.append(sink("=$q").rstrip("\n"))
    return "\n".join(lines) + "\n"


