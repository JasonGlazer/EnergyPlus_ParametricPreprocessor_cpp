def sink(expression):
    """An informational Output:PreprocessorMessage whose first message line is the expression.

    Any text is accepted there (unlike an Output:Variable key, which is a regular expression),
    the object can repeat, and the expression is ended by a comma like a field in the middle
    of an object.
    """
    return f"  Output:PreprocessorMessage,ParametricTest,Information,{expression},result;\n"


def sinks(expressions):
    return "".join(sink(e) for e in expressions)


def shading(kind, name, x, height, last_expression=None):
    """A detached shading surface 20 m south of the building: removable without side effects."""
    height_field = last_expression if last_expression else height
    return (f"  {kind},\n"
            f"    {name},{'':{max(1, 21 - len(name))}}!- Name\n"
            f"    0, 90, {x}, -20, 0, 3,   !- Azimuth, Tilt, Starting X, Y, Z, Length\n"
            f"    {height_field};{'':{max(1, 20 - len(str(height_field)))}}!- Height {{m}}\n")


def build(header, block="", omit=(), transform=None):
    """Assemble one input: header comment, Version, the test block, then the base model."""
    text = "".join(f"! {line}\n" if line else "!\n" for line in header.strip("\n").split("\n"))
    text += GENERATED + "\n\n"
    objects = [(kind, obj) for kind, obj in BASE if kind not in omit]
    if transform:
        objects = [(kind, transform(obj)) for kind, obj in objects]
    if objects and objects[0][0] == "Version":
        text += objects.pop(0)[1] + "\n"
    if block:
        text += block.rstrip("\n") + "\n\n"
    text += "! ---- base model ----\n\n"
    text += "\n".join(obj for _, obj in objects)
    return text


def last_field_as_expression(obj):
    """Write the last field of an object as a string expression ( value;  ->  ="value"; )."""
    lines = obj.rstrip("\n").split("\n")
    for i in range(len(lines) - 1, -1, -1):
        code, sep, comment = lines[i].partition("!")
        if ";" in code:
            head, _, tail = code.rpartition(";")
            fields = head.split(",")
            value = fields[-1].strip()
            indent = fields[-1][: len(fields[-1]) - len(fields[-1].lstrip())]
            fields[-1] = f'{indent}="{value}"'
            lines[i] = ",".join(fields) + ";" + tail + sep + comment
            break
    return "\n".join(lines) + "\n"


