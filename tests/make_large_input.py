#!/usr/bin/env python3
"""Generate tests/inputs/coverage_large_input.idf.

The Fortran original stores everything in arrays that start small and are doubled when
full. This input is large enough to make every one of those arrays grow at least once:

  array               initial size   this input
  IdfObject           20             26 Parametric objects
  IdfField            200            276 fields in Parametric objects
  ObjectLines         500            521 objects
  FoundExpression     100            520 embedded expressions
  Symbol              500            507 parameters, then more than 500 constants
  IntCode             1000           more than 1500 codes
  StrucStack          50             55 nested IF blocks
  EvalStack           50             60 values left on the stack by MOD (see PORTING_NOTES.md)
  ErrMsgs             100            105 warnings

Only the first case is run (Parametric:RunControl) to keep the expected output small.
"""

from pathlib import Path

NUM_CASES = 10
NUM_PARAMETERS = 25
NUM_OBJECTS = 520
NESTING = 55
LEFTOVERS = 60
WARNINGS = 105
EXTRA_PARAMETERS = 480


def main() -> None:
    lines = ["! Generated by tests/make_large_input.py - grows every Fortran array", "Version,9.6;", ""]
    lines.append("  Parametric:RunControl, Runs, Yes" + ", No" * (NUM_CASES - 1) + ";")
    for p in range(1, NUM_PARAMETERS + 1):
        values = ", ".join(str(p * 10 + c) for c in range(NUM_CASES))
        lines.append(f"  Parametric:SetValueForRun, $p{p}, {values};")
    logic = ["PARAMETER $depth", "PARAMETER $q"]
    logic += [f"PARAMETER $extra{i}" for i in range(EXTRA_PARAMETERS)]
    logic += ["IF 1"] * NESTING + ["$depth = 99"] + ["ENDIF"] * NESTING
    logic += ["$q = MOD(7~3)"] * LEFTOVERS
    logic += [f"NOT A STATEMENT {i}" for i in range(WARNINGS)]
    lines.append("  Parametric:Logic, Main,\n    " + ",\n    ".join(logic) + ";")
    lines.append("")
    for i in range(1, NUM_OBJECTS + 1):
        lines.append(f"  Shading:Site, Obj{i}, =$p{(i % NUM_PARAMETERS) + 1} + {i}, 1;")
    lines.append("  Output:Variable, =$depth, =$q, hourly;")
    out = Path(__file__).parent / "inputs" / "coverage_large_input.idf"
    out.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
